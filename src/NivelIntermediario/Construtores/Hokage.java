package NivelIntermediario.Construtores;

public class Hokage {

    String nome;
    int idade;
    boolean VivoOuMorto;

    public Hokage() {
    }

    public Hokage(String nome, int idade, boolean vivoOuMorto) {
        this.nome = nome;
        this.idade = idade;
        VivoOuMorto = vivoOuMorto;
    }
}
